using StockBar;
using System.Text.Json;

int count = 0;
void Check(bool value, string name) { if (!value) throw new Exception(name); count++; }
var now = DateTimeOffset.UtcNow;
var s = new Snapshot { Connected = true, FetchedAt = now, Price = 100, ChangePercent = 5 };
Check(!s.IsStale(now), "fresh connection");
Check(s.IsStale(now.AddSeconds(31)), "worker hang becomes stale");
Check((s with { Connected = false }).IsStale(now), "disconnected cannot look live");
Check((s with { Price = double.NaN }).DisplayPrice == "—", "NaN never displays as a quote");
Check((s with { Price = 0 }).DisplayPrice == "—", "zero price is unavailable");
var parsed = JsonSerializer.Deserialize<Snapshot>("{\"connected\":true,\"price\":105,\"changePercent\":5,\"points\":[]}", Snapshot.JsonOptions)!;
Check(parsed.DisplayPrice == "$105.00", "bridge camelCase contract");
Check(parsed.DisplayChange == "+5.00%", "positive percentage sign");
Check((s with { Price = null }).DisplayChange == "—", "no percentage without valid price");
var flat = ChartMath.Project([new QuotePoint("2026-10-27 09:30:00", 100, "盘中")], 400, 140, 100);
Check(flat.Count == 1 && double.IsFinite(flat[0].Y), "single flat point safe");
Check(ChartMath.Project([], 400, 140, null).Count == 0, "empty chart safe");
Check(ChartMath.Project([new QuotePoint("bad", 100, "盘中")], 400, 140, null).Count == 0, "bad time ignored");
var placement = TickerLayout.Default(1920, 1080, 1040);
Check(placement.Left == 120 && placement.Top == 1044, "ticker occupies weather-right taskbar space");
Check(placement.Top + TickerLayout.Height <= 1080, "ticker stays inside screen");
Check(TickerLayout.ExpandedTop(placement.Top) + TickerLayout.PanelHeight == placement.Top, "expansion keeps ticker anchored");
Console.WriteLine($"PASS {count} checks");
var list = WatchlistParser.Parse("WDC.US,NVDA,US.MU,WDC");
Check(string.Join(",", list) == "WDC,NVDA,MU", "normalize moomoo codes without duplicate stocks");
Check(WatchlistParser.Parse("\"代码\",\"名称\",\"最新价\"\n\"WDC.US\",\"西部数据\",\"396.42\"\n\"005930.KR\",\"三星\",\"242000\"").SequenceEqual(new[] { "WDC", "005930.KS" }), "CSV prices never become stock codes");
Check(WatchlistParser.Parse("603004.SH\nBTC.CC\nUS10Y.BD\nCLmain.US").SequenceEqual(new[] { "603004.SS", "BTC-USD", "^TNX", "CL=F" }), "map actual moomoo non-stock symbols");
Check(WatchlistParser.Parse("../../bad\n396.42\n名称").Count == 0, "invalid entries do not become requests");
var feed = new MarketFeed { Quotes = new() { ["NVDA"] = new Snapshot { Symbol = "WDC", Price = 100 } } };
Check(!feed.ForSymbol("NVDA").HasPrice, "wrong-symbol response cannot display a quote");
Check((s with { Currency = "KRW", Price = 242000 }).DisplayPrice == "₩242,000", "foreign prices never labeled dollars");
Console.WriteLine($"PASS {count} total checks");
var live = SessionStyle.For("盘中");
Check(live.Fore == "#58DCAF", "regular session reads as live green");
Check(SessionStyle.For("盘后").Fore != live.Fore, "post market is never painted as regular session");
Check(SessionStyle.For("盘前").Fore != live.Fore, "pre market is never painted as regular session");
Check(SessionStyle.For("断线") == SessionStyle.For("不存在的状态"), "disconnected and unknown share the neutral chip");
Check(SessionStyle.For("休市") != live, "closed market never wears the live colour");
Console.WriteLine($"PASS {count} total checks");
var localCatalog = new WatchlistConfig { Symbols = new() { "WDC", "NVDA" }, Names = new() { ["WDC"] = "西部数据", ["NVDA"] = "英伟达" } };
Check(SearchCatalog.Local("英伟", localCatalog, Array.Empty<string>()).Single().Symbol == "NVDA", "Chinese company names find imported symbols");
Check(WatchlistParser.Normalize("ADBE") == "ADBE", "search accepts stocks outside imported list");
Console.WriteLine($"PASS {count} total checks");
